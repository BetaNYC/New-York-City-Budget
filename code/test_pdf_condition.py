LETTER = (612, 792)
SENTENCE = "The quick brown fox jumps over the lazy dog 0123456789. "


# --- fixture builder ---------------------------------------------------------------------------
def make_pdf(path, pages):
    """Write a minimal valid PDF. `pages` is a list of dicts: text (str), invisible (bool),
    grid (int rows, int cols) or None, image (bool, full-page black DeviceGray image)."""
    objs = []  # list of bytes, object number = index + 1

    def add(body: bytes) -> int:
        objs.append(body)
        return len(objs)

    font = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
               b"/Encoding /WinAnsiEncoding >>")
    img = add(b"<< /Type /XObject /Subtype /Image /Width 8 /Height 8 /ColorSpace /DeviceGray "
              b"/BitsPerComponent 8 /Length 64 >>\nstream\n" + bytes(64) + b"\nendstream")
    pages_num = len(objs) + 1 + 2 * len(pages)  # reserve: each page = content + page object
    kids = []
    for spec in pages:
        ops = []
        if spec.get("image"):
            ops.append(b"q 612 0 0 792 0 0 cm /Im1 Do Q")
        grid = spec.get("grid")
        if grid:
            rows, cols = grid
            x0, x1, y_top, row_h = 72, 540, 700, 20
            col_w = (x1 - x0) / cols
            for r in range(rows + 1):
                y = y_top - r * row_h
                ops.append(f"{x0} {y} m {x1} {y} l S".encode())
            for c in range(cols + 1):
                x = x0 + c * col_w
                ops.append(f"{x:.1f} {y_top} m {x:.1f} {y_top - rows * row_h} l S".encode())
        text = spec.get("text", "")
        if text:
            mode = 3 if spec.get("invisible") else 0
            ops.append(f"BT /F1 9 Tf {mode} Tr 11 TL 50 600 Td".encode())
            for i in range(0, len(text), 90):
                chunk = text[i:i + 90].replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
                ops.append(f"({chunk}) Tj T*".encode("latin-1"))
            ops.append(b"ET")
        stream = b"\n".join(ops)
        content = add(b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream")
        page = add(b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 %d %d] "
                   b"/Resources << /Font << /F1 %d 0 R >> /XObject << /Im1 %d 0 R >> >> "
                   b"/Contents %d 0 R >>" % (pages_num, LETTER[0], LETTER[1], font, img, content))
        kids.append(page)
    assert len(objs) + 1 == pages_num
    add(b"<< /Type /Pages /Kids [" + b" ".join(b"%d 0 R" % k for k in kids)
        + b"] /Count %d >>" % len(kids))
    catalog = add(b"<< /Type /Catalog /Pages %d 0 R >>" % pages_num)
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += (b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(objs) + 1, catalog, xref))
    with open(path, "wb") as fh:
        fh.write(bytes(out))
    return path


TEXT = SENTENCE * 8  # ~450 chars, well above the 100 chars/page gate


@pytest.fixture
def corpus(tmp_path):
    src = tmp_path / "source" / "FY27"
    src.mkdir(parents=True)
    make_pdf(src / "Fiscal-2027-Schedule-C-ruled.pdf",
             [{"text": TEXT, "grid": (4, 5)}, {"text": TEXT, "grid": (4, 5)}])
    make_pdf(src / "FY27-Terms-and-Conditions.pdf", [{"text": TEXT}, {"text": TEXT}])
    make_pdf(src / "ocr-layer.pdf", [{"image": True, "text": TEXT, "invisible": True}])
    make_pdf(src / "scan.pdf", [{"image": True}, {"image": True}])
    make_pdf(src / "mixed.pdf", [{"text": TEXT}, {"text": TEXT}, {"image": True}])
    make_pdf(src / "blank-page.pdf", [{"text": TEXT}, {}, {"text": TEXT}])
    return tmp_path


def row_for(tmp_path, name):
    with open(tmp_path / "data" / "pdf_condition.csv", newline="") as fh:
        for r in csv.DictReader(fh):
            if r["path"].endswith(name):
                return r
    raise AssertionError(name)


@pytest.fixture
def surveyed(corpus):
    pc.run(corpus / "source", corpus / "data", corpus, workers=1)
    return corpus


# --- end to end ------------------------------------------------------------------------------
def test_born_digital_ruled_is_tier_a(surveyed):
    r = row_for(surveyed, "Schedule-C-ruled.pdf")
    assert r["textlayer_class"] == "text" and r["text_class"] == "text"
    assert r["qa_tier"] == "A" and r["ruled_table_pages"] == "2"
    assert r["family"] == "schedule_c" and r["fiscal_year"] == "2027"
    assert r["invisible_char_share"] == "0.0"


def test_born_digital_unruled_is_tier_b(surveyed):
    r = row_for(surveyed, "Terms-and-Conditions.pdf")
    assert (r["text_class"], r["qa_tier"], r["ruled_table_pages"]) == ("text", "B", "0")
    assert r["family"] == "terms_conditions" and r["family_basis"] == "filename"


def test_invisible_text_over_image_is_ocr_layer(surveyed):
    r = row_for(surveyed, "ocr-layer.pdf")
    assert r["textlayer_class"] == "scanned-ocr-layer" and r["qa_tier"] == "C"
    assert float(r["invisible_char_share"]) == 1.0


def test_image_only_scan_is_tier_d(surveyed):
    r = row_for(surveyed, "scan.pdf")
    assert (r["textlayer_class"], r["qa_tier"]) == ("scanned", "D")
    assert r["image_only_pages"] == "1-2" and r["pages_with_images"] == "2"


def test_image_only_page_inside_text_document_is_caught(surveyed):
    # The mean (~300 chars/page) passes the gate; the per-page view must still catch page 3.
    r = row_for(surveyed, "mixed.pdf")
    assert r["textlayer_class"] == "text"
    assert r["text_class"] == "mixed" and "mixed" in r["special_flags"]
    assert r["low_text_pages"] == "3" and r["image_only_pages"] == "3"


def test_blank_page_is_not_image_only(surveyed):
    r = row_for(surveyed, "blank-page.pdf")
    assert r["text_class"] == "text"
    assert r["low_text_pages"] == "2" and r["blank_pages"] == "2" and r["image_only_pages"] == ""


def test_pages_csv_has_every_page_and_page_tiers(surveyed):
    with open(surveyed / "data" / "pdf_condition_pages.csv", newline="") as fh:
        rows = list(csv.DictReader(fh))
    assert len(rows) == 2 + 2 + 1 + 2 + 3 + 3
    tiers = {(r["path"].rsplit("/", 1)[1], r["page"]): r["page_tier"] for r in rows}
    assert tiers[("mixed.pdf", "3")] == "D" and tiers[("mixed.pdf", "1")] == "B"
    assert tiers[("blank-page.pdf", "2")] == "blank"
    assert tiers[("ocr-layer.pdf", "1")] == "C"
    ruled = next(r for r in rows if r["path"].endswith("Schedule-C-ruled.pdf"))
    assert (ruled["h_rules"], ruled["v_rules"]) == ("5", "6")


def test_output_is_deterministic(corpus):
    pc.run(corpus / "source", corpus / "a", corpus, workers=2)
    pc.run(corpus / "source", corpus / "b", corpus, workers=1)
    for name in ("pdf_condition.csv", "pdf_condition_pages.csv"):
        assert (corpus / "a" / name).read_bytes() == (corpus / "b" / name).read_bytes()


def test_lfs_pointer_fails_loud(tmp_path):
    src = tmp_path / "source"
    src.mkdir()
    (src / "pointer.pdf").write_text("version https://git-lfs.github.com/spec/v1\noid sha256:ab\n")
    with pytest.raises(SystemExit, match="LFS"):
        pc.run(src, tmp_path / "data", tmp_path, workers=1)


def test_encrypted_pdf_is_flagged(tmp_path):
    pypdf = pytest.importorskip("pypdf")
    plain = make_pdf(tmp_path / "plain.pdf", [{"text": TEXT}])
    w = pypdf.PdfWriter(clone_from=str(plain))
    w.encrypt(user_password="", owner_password="owner", algorithm="RC4-128")
    enc = tmp_path / "enc.pdf"
    with open(enc, "wb") as fh:
        w.write(fh)
    row = pc.doc_row(pc.survey_pdf(enc, "enc.pdf"))
    assert row["encrypted"] is True and "encrypted" in row["special_flags"]
    assert row["textlayer_class"] == "text"



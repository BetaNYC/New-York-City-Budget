def test_low_text_pages_only_inside_a_passing_document():
    assert pc.low_text_pages([2000, 0, 50]) == [2, 3]
    assert pc.low_text_pages([0, 0, 50]) == []


def test_garbled_chars():
    assert pc.is_garbled_char("�") and pc.is_garbled_char("")  # PUA bullet
    assert pc.is_garbled_char("\x01")
    assert not pc.is_garbled_char("a") and not pc.is_garbled_char("\n")


def test_rule_geometry():
    assert pc.classify_segment(0, 0, 100, 0.5) == "h"
    assert pc.classify_segment(0, 0, 0.4, 50) == "v"
    assert pc.classify_segment(0, 0, 30, 30) is None   # diagonal
    assert pc.classify_segment(0, 0, 2, 0) is None     # too short
    assert pc.classify_box(200, 0.7) == "h" and pc.classify_box(0.7, 28) == "v"
    assert pc.classify_box(50, 20) == "rect" and pc.classify_box(1, 1) is None


# --- unit: family is never guessed ---------------------------------------------------------
def test_family_agreement_single_signal_conflict_and_silence():
    by_name = pc.family_from_filename("FY18-Sec254-Capital-ResoA-M499-Res1534-Res1535.pdf")
    by_title = pc.family_from_title("Supporting Detail For Fiscal Year 2018 Changes to the "
                                    "Executive Capital Budget")
    assert (by_name, by_title) == ("capital_changes", "capital_supporting_detail")
    assert pc.resolve_family(by_name, by_title) == ("unknown", "conflict")
    assert pc.resolve_family("schedule_c", "schedule_c") == ("schedule_c", "filename+title")
    assert pc.resolve_family(None, "schedule_c") == ("schedule_c", "title")
    assert pc.resolve_family(None, None) == ("unknown", "none")



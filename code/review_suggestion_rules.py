    if not by_id:
        checks = [e for e in entries if isinstance(e[3], dict) and e[3]["check_id"] == r["check_id"]]
        by_sub = [e for e in checks if "sub_id" in e[3] and e[3]["sub_id"] == r.get("sub_id")]
        by_id = by_sub or [e for e in checks if "sub_id" not in e[3]]
    if len(by_id) != 1:
        raise SystemExit(f"FY{fy} {family} {r['review_id']} ({r['check_id']}): "
                         f"{len(by_id)} rules match in {md}")
    item, decision, note, _ = by_id[0]
    assert decision in DECISIONS or decision == "", decision
    return decision, note, f"{md} {item}"

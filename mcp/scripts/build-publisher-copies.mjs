#!/usr/bin/env node
/**
 * build-publisher-copies.mjs — writes src/publisher-copies.ts, the publisher's copy of each source
 * PDF we know one for, keyed by sha256, for rowlinks.ts (the third of a row's three links).
 *
 * Read from source/gpp/MANIFEST.csv: every file downloaded from the City's Government Publications
 * Portal, with its sha256 and the portal's URL. A row's PDF gets a publisher link only when its
 * pdf_sha256 equals one of these byte for byte; no URL is ever guessed from a file name. No other
 * manifest in source/ records a URL for a PDF (the others are spreadsheets and Open Data).
 *
 * The output is committed, so the npm package and the explorer build need no CSV at run time.
 * test/rowlinks.test.js fails if the committed file differs from what this script writes.
 *
 *   node scripts/build-publisher-copies.mjs          # rewrite src/publisher-copies.ts
 *   node scripts/build-publisher-copies.mjs --check  # exit 1 if it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "csv-parse/sync";

const MCP = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(MCP, "..");
export const MANIFESTS = ["source/gpp/MANIFEST.csv"];
export const OUT = join(MCP, "src", "publisher-copies.ts");

export function render() {
  const copies = new Map();
  for (const rel of MANIFESTS) {
    const rows = parse(readFileSync(join(REPO, rel), "utf8"), { columns: true, skip_empty_lines: true, bom: true });
    for (const r of rows) {
      const sha = String(r.sha256 ?? "").trim().toLowerCase();
      if (!/^[0-9a-f]{64}$/.test(sha) || !/^https:\/\//.test(r.url ?? "") || String(r.http_status) !== "200") continue;
      if (copies.has(sha)) continue;
      copies.set(sha, {
        url: r.url,
        item_url: r.item_url || null,
        title: r.title || null,
        publisher: r.agency || null,
        retrieved_at: r.retrieved_at || null,
        manifest: rel,
      });
    }
  }
  const body = [...copies.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([sha, c]) => `  ${JSON.stringify(sha)}: ${JSON.stringify(c)},`)
    .join("\n");
  return `// GENERATED by scripts/build-publisher-copies.mjs from ${MANIFESTS.join(", ")}. Do not edit.
// The publisher's copy of a source PDF, keyed by the file's sha256 (rowlinks.ts, publisherCopy).

export interface PublisherCopy {
  url: string;
  item_url: string | null;
  title: string | null;
  publisher: string | null;
  retrieved_at: string | null;
  manifest: string;
}

export const PUBLISHER_COPIES: Readonly<Record<string, PublisherCopy>> = {
${body}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    const now = readFileSync(OUT, "utf8");
    if (now !== text) {
      console.error("src/publisher-copies.ts is out of date: run node scripts/build-publisher-copies.mjs");
      process.exit(1);
    }
    console.log("src/publisher-copies.ts is up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
